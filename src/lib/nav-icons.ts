export type NavIcon = keyof typeof NAV_ICONS;

/** The icon for a name from the model (the grid for a name that isn't here, which the tests rule out). */
export function navIcon(name: string | undefined): LucideIcon {
  return name && Object.hasOwn(NAV_ICONS, name) ? NAV_ICONS[name as NavIcon] : LayoutGrid;
}
